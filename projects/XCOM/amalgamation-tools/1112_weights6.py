print('entries old %d new %d | dropped %d | added %d | changed %d' % (len(oldw), len(neww), len(set(oldw) - set(neww)), len(set(neww) - set(oldw)), sum(1 for k in neww if k in oldw and oldw[k] != neww[k])))
live_names = {n for n, _ in w}
print('entries naming a class outside the deck:', sorted(set(neww) - live_names))
for n in ('HareCaptain_HareBuckler_SkvScout', 'HareCaptain_HareBuckler_Smoker', 'Pistoleer_HareSwash_SkvAssassin'):
    print('  ', n, dict(w).get(n))
if '--apply' in sys.argv:
    shutil.copyfile(LIVE, TMP + 'XComjepClassWeights.ini.bak-1112')
    open(LIVE, 'wb').write(txt)
    print('APPLIED')
