"""Regenerate jepClassWeights config on the live deck (weights5 logic unchanged). Dry run by default; --apply writes live + backup."""
import os, sys, io, json, shutil, re, contextlib
OLD = 'C:/Users/jep/.claude/jobs/94ad0c55/tmp'
TMP = 'C:/Users/jep/.claude/jobs/0815ca4d/tmp/'
sys.path.insert(0, OLD)
os.chdir(TMP)
buf = io.StringIO()
with contextlib.redirect_stdout(buf):
    exec(open(OLD + '/weights5.py').read())
out = buf.getvalue(); print(out)
w = json.load(open(TMP + 'weights_out.json'))
m = re.search(r'weighted\s+8 weaponless.*median (\d+), worst of 40 runs (\d+)', out)
med, worst = m.group(1), m.group(2)
nspec = len({('P', c[0]) for c in deck} | {('S', c[1]) for c in deck} | {('T', c[2]) for c in deck})
rows = sorted((n, k) for n, k in w if k > 1)
cfg = ['; jepClassWeights 2026-11-12: Choose My Class tickets per Amalgamation class (default 1; classes at 1 ticket are not listed).',
       '; Generated by weights5.py on the %d-card deck (11-12 batch: Oddsman x Ironclad cut, Buckler moved to Captain, Swash gets Assassin).' % len(w),
       '; Rarest spec of the three sets the boost, cap 50; secondaries held to <=8 %.',
       '; Simulated: all %d specs seen within a median of %s promotions of 100 offers (worst of 40 runs %s).' % (nspec, med, worst),
       '', '[jepClassWeights.X2DownloadableContentInfo_jepClassWeights]']
cfg += ['+Weights=(ClassName="%s", Tickets=%d)' % (n, k) for n, k in rows]
txt = ('\r\n'.join(cfg) + '\r\n').encode('ascii')
LIVE = "C:/Program Files (x86)/Steam/steamapps/common/XCOM 2/XCom2-WarOfTheChosen/XComGame/Mods/jepClassWeights/Config/XComjepClassWeights.ini"
