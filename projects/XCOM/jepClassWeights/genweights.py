"""Write the jepClassWeights mod's metadata + config from weights_out.json (only classes with >1 ticket)."""
import json, os
M = 'C:/Users/jep/.claude/jobs/94ad0c55/tmp/jepClassWeights/'
os.makedirs(M + 'Config', exist_ok=True)
w = json.load(open('C:/Users/jep/.claude/jobs/94ad0c55/tmp/weights_out.json'))
rows = sorted((n, k) for n, k in w if k > 1)
cfg = ['; jepClassWeights 2026-11-08: Choose My Class tickets per Amalgamation class (default 1). Generated by weights5.py',
       '; on the 611-card deck (rule D4 cut). Rarest spec of the three sets the boost, cap 50; secondaries held to <=8 %.',
       '; Simulated: all 141 specs seen within a median of 5 promotions of 100 offers (worst of 40 runs 7).',
       '', '[jepClassWeights.X2DownloadableContentInfo_jepClassWeights]']
cfg += ['+Weights=(ClassName="%s", Tickets=%d)' % (n, k) for n, k in rows]
open(M + 'Config/XComjepClassWeights.ini', 'w', newline='\r\n').write('\n'.join(cfg) + '\n')
open(M + 'Config/XComEditor.ini', 'w', newline='\r\n').write('[ModPackages]\n+ModPackages=jepClassWeights\n')
open(M + 'Config/XComEngine.ini', 'w', newline='\r\n').write('[Engine.ScriptPackages]\n+NonNativePackages=jepClassWeights\n')
open(M + 'jepClassWeights.XComMod', 'w', newline='\r\n').write(
    '[mod]\npublishedFileId=0\nTitle=jepClassWeights\nDescription=Choose My Class tickets per Amalgamation class (rare specs show up more often). Built by jep, 2026-11-08.\nRequiresXPACK=true\n')
print('weighted classes', len(rows), 'of', len(w), '| tickets total', sum(k for _, k in w))
